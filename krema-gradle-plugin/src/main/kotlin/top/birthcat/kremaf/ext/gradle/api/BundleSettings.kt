package top.birthcat.kremaf.ext.gradle.api

import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputFile
import org.gradle.api.tasks.Internal
import org.gradle.api.tasks.Optional
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import top.birthcat.kremaf.ext.gradle.internal.config.appJarName
import java.io.Serializable
import java.nio.file.Path

/**
 * Identity inputs for packaging: what the app is called, what it says about itself and which icon it carries.
 *
 * The app-image layout and its launcher are generated by jpackage; this type only holds
 * the identity that ends up in artifact names and platform metadata.
 */
data class BundleSettings(
    /** Application name, used for the app-image directory, launcher and artifact names. */
    @get:Input val appName: String,
    /** Reverse-DNS identity; macOS needs it explicitly, other platforms ignore it. */
    @get:Input val identifier: String,
    /** Version passed to jpackage as `--app-version`. */
    @get:Input val version: String,
    /** Fully qualified main class recorded in the generated launcher. */
    @get:Input val mainClass: String,
    /** Optional icon; absent means jpackage runs without `--icon`. */
    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    @get:Optional
    val icon: Path? = null,
    /** Optional summary, passed to jpackage as `--description`. */
    @get:Input
    @get:Optional
    val description: String? = null,
    /** Optional copyright notice, passed to jpackage as `--copyright`. */
    @get:Input
    @get:Optional
    val copyright: String? = null,
) : Serializable {
    /** Application jar name, passed to jpackage as `--main-jar`. */
    @get:Internal
    val appJarName get() = appJarName(appName)
}
